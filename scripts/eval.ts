// Usage: npx tsx scripts/eval.ts [seeds]   Writes docs/evaluation.md from a fresh, deterministic run.
import fs from 'node:fs';
import { runEvaluation } from '@/lib/evaluation';

const seeds = Number(process.argv[2] ?? 16);
const r = runEvaluation(seeds, 100);
const pc = (x: number, d = 1) => `${(x * 100).toFixed(d)}%`;
const n2 = (x: number) => x.toFixed(2);
const label: Record<string, string> = {
  rules: 'Madoun rules (hand-set weights)', challenger: 'Learned challenger (logistic regression, advisory)', 'trader-only': 'Trader compliance score alone', 'value-only': 'Declared value alone', random: 'Random',
};
const seg: Record<string, string> = { 'band:low': 'Trader compliance below 60', 'band:mid': 'Trader compliance 60 to 79', 'band:high': 'Trader compliance 80 and above', 'aeo:yes': 'Authorised operators', 'aeo:no': 'Other traders' };

const md = `# Model evaluation

Generated by \`npm run eval\` (${seeds} synthetic weeks, seeds 100 to ${99 + seeds}; the first half fits the learned challenger, the second half scores every method). Deterministic: rerunning gives the same numbers. The demo itself uses seed 2026, which is never part of this evaluation.

> **Read this first.** The synthetic generator decides which shipments hide a violation from the trader's compliance score and from under-declared value. The rule engine reads the same facts. Scores here are therefore optimistic and partly circular. This evaluation can expose a weak, uneven or beaten rule set; it cannot show the rules work on real traffic. Real validation needs labelled historical outcomes from customs.

## Population
- ${r.shipments} shipments, ${r.violations} with a hidden violation (${pc(r.baseRate.rate)}, 95% range ${pc(r.baseRate.lo)} to ${pc(r.baseRate.hi)}).
- Scored on a held-out half: ${r.testShipments} shipments, ${r.testViolations} violations.

## Do the lanes order risk?
| Lane | Shipments | With a violation | Rate | 95% range |
|---|---:|---:|---:|---|
${r.lanes.map((l) => `| ${l.lane} | ${l.n} | ${l.violations} | ${pc(l.rate)} | ${pc(l.lo)} to ${pc(l.hi)} |`).join('\n')}

Madoun checks ${pc(r.policy.burden)} of shipments (amber and red) and catches ${pc(r.policy.recall)} of violations (95% range ${pc(r.policy.recallCI.lo)} to ${pc(r.policy.recallCI.hi)}). Precision of a check is ${pc(r.policy.precision)}. **${r.policy.missedInGreen} violations (${pc(1 - r.policy.recall)}) passed through the green lane.** Random audits of green traffic exist to measure exactly this.

## Rules against simpler and learned alternatives (held-out half)
| Method | AUC (95% bootstrap range) | Average precision | Violations found at the same effort |
|---|---|---:|---:|
${r.methods.map((m) => `| ${label[m.name]} | ${n2(m.auroc)} (${n2(m.aurocCI.lo)} to ${n2(m.aurocCI.hi)}) | ${n2(m.averagePrecision)} | ${pc(m.recallAtSameBurden)} |`).join('\n')}

"Same effort": each method may check as many shipments as the rules do (the number sent to amber or red) and we count the violations among them.

What this says:
${(() => {
  const g = (n: string) => r.methods.find((m) => m.name === n)!;
  const lines: string[] = [];
  lines.push(`- The rules rank risk far better than chance (AUC ${n2(g('rules').auroc)} against ${n2(g('random').auroc)}).`);
  const gap = g('rules').auroc - g('trader-only').auroc;
  lines.push(`- The trader's compliance score alone reaches AUC ${n2(g('trader-only').auroc)}, ${gap < 0.05 ? 'close to the full rule set' : 'below the full rule set'} (difference ${n2(gap)}).${gap < 0.05 ? " Much of the engine's strength comes from that one fact." : ''}`);
  const lift = g('challenger').auroc - g('rules').auroc;
  lines.push(`- The learned challenger scores ${n2(g('challenger').auroc)} (${lift > 0 ? '+' : ''}${n2(lift)}) and finds ${pc(g('challenger').recallAtSameBurden)} of violations at the rules' effort against ${pc(g('rules').recallAtSameBurden)}. ${g('challenger').aurocCI.lo > g('rules').aurocCI.hi ? 'The ranges do not overlap.' : 'The ranges overlap, so the gain is not established.'} It is not used to decide lanes: promotion needs a stable gain on held-out data, calibration, no worse burden on any group, and sign-off.`);
  return lines.join('\n');
})()}

### Challenger calibration (held-out)
Brier score ${r.challenger.brier.toFixed(3)} against ${r.challenger.baselineBrier.toFixed(3)} for always predicting the training average (lower is better).

| Predicted | Shipments | Mean predicted | Observed |
|---|---:|---:|---:|
${r.challenger.calibration.map((b) => `| ${pc(b.from, 0)} to ${pc(b.to, 0)} | ${b.n} | ${pc(b.meanPredicted)} | ${pc(b.observed)} |`).join('\n')}

### Challenger coefficients (standardised; positive raises risk)
| Feature | Weight |
|---|---:|
${r.challenger.coefficients.map((c) => `| ${c.name} | ${c.weight.toFixed(3)} |`).join('\n')}

The generator does not use goods category, route or document gaps to decide violations, so the challenger rightly gives them about zero or odd-signed weight. That is a property of the synthetic data, not a finding about customs.

## Who bears the checks?
| Group | Shipments | Checked | Checks that found nothing | 95% range |
|---|---:|---:|---:|---|
${r.segments.map((s) => `| ${seg[s.key]} | ${s.n} | ${pc(s.flaggedPct)} | ${s.flagged ? pc(s.falseFlagRate) : '–'} | ${s.flagged ? `${pc(s.lo)} to ${pc(s.hi)}` : '–'} |`).join('\n')}

Every shipment from a low-compliance trader is sent to amber or red. That is blanket treatment of a class of traders, not a per-shipment risk judgement, and it should be a stated policy choice (proportionality, TFA Article 7.4) rather than a side effect of weights.

## What the unbiased sample adds
The learning loop only sees outcomes for shipments something chose to check, so its hit rates describe a selected group. Madoun now audits flagged green shipments after release (never delaying them), and a hash-selected 1 in 20 of green traffic is a true random sample. Its outcome rate is the only base rate that is not shaped by the rules.
`;
fs.writeFileSync('docs/evaluation.md', md);
console.log(md.split('\n').slice(0, 40).join('\n'));
