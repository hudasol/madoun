/**
 * Runs the preregistered inspection cell experiment (docs/preregistration-cell.md) and writes
 * docs/cell-results.json and docs/cell-experiment.md. Deterministic: the same code gives the same files.
 *   npm run cell
 */
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import {
  CELL_BASE, CELL_METRICS, CELL_SCENARIOS, CELL_SEEDS, checkCellPredictions, runCellExperiment,
  type CellMetric, type CellScenarioId, type Interval,
} from '../src/engine/cell';

// Six decimals: enough that rounding again for display (two decimals) gives the same digits as the report.
const r6 = (x: number) => (Number.isFinite(x) ? Math.round(x * 1e6) / 1e6 : null);
const ivJson = (i: Interval) => ({ mean: r6(i.mean), lo: r6(i.lo), hi: r6(i.hi), sd: r6(i.sd), n: i.n });

export function buildCellReport(): { json: string; markdown: string } {
  const x = runCellExperiment(CELL_SEEDS);
  const checks = checkCellPredictions(x);
  const result = {
    generatedBy: 'npm run cell',
    preregistration: 'docs/preregistration-cell.md',
    note: 'Synthetic model. Every parameter is an assumption stated in the preregistration, not a measurement.',
    seeds: x.seeds,
    params: CELL_BASE,
    scenarios: CELL_SCENARIOS.map((s) => ({
      id: s.id, name: s.name, nameAr: s.nameAr,
      robot: s.params.mode === 'robots' ? { faultProb: s.params.robot.faultProb, recoveryHours: s.params.robot.recoveryHours } : null,
      summary: Object.fromEntries(CELL_METRICS.map((m) => [m, ivJson(x.summary[s.id][m])])),
    })),
    conservation: { runs: x.runs.length, allConserved: x.runs.every((r) => r.conserved), tasks: x.runs.reduce((a, r) => a + r.tasks, 0) },
    predictions: checks,
    // Counted over predictions that can fail; P6 is a structural invariant reported on its own (amendment A2).
    hits: checks.filter((c) => c.kind === 'prediction' && c.hit).length,
    misses: checks.filter((c) => c.kind === 'prediction' && !c.hit).length,
    predictionCount: checks.filter((c) => c.kind === 'prediction').length,
    invariantsHeld: checks.filter((c) => c.kind === 'invariant').every((c) => c.hit),
  };

  const S = x.summary;
  const fh = (i: Interval) => (Number.isFinite(i.mean) ? `${i.mean.toFixed(2)} [${i.lo.toFixed(2)}, ${i.hi.toFixed(2)}]` : 'not applicable');
  const fp = (i: Interval) => `${(i.mean * 100).toFixed(1)}% [${(i.lo * 100).toFixed(1)}, ${(i.hi * 100).toFixed(1)}]`;
  const machineOnly: CellMetric[] = ['p90ConfirmDelay', 'confirmedBeforeCompletion'];
  const row = (label: string, m: CellMetric, f: (i: Interval) => string) =>
    `| ${label} | ${CELL_SCENARIOS.map((s) => (machineOnly.includes(m) && s.params.mode !== 'robots' ? 'not applicable' : f(S[s.id][m]))).join(' | ')} |`;
  const scen = (id: CellScenarioId) => CELL_SCENARIOS.find((s) => s.id === id)!.name;
  const runsOf = (id: CellScenarioId) => x.runs.filter((r) => r.scenario === id);
  const avg = (id: CellScenarioId, k: 'tasks' | 'violations' | 'seriousMachineFindings' | 'robotFaults') => (runsOf(id).reduce((a, r) => a + r[k], 0) / runsOf(id).length).toFixed(1);

  const md = `# Inspection cell experiment: results

Generated by \`npm run cell\` from \`src/engine/cell.ts\`. Do not edit by hand; a test fails if this file differs from a fresh run.
Preregistration: [docs/preregistration-cell.md](preregistration-cell.md), committed in its own commit (4b012c9) before the commit that added the model (5fc7f0c). The git history is the only timestamp; there is no external one. Amendments A1 and A2 are recorded there.

**Read this first.** This is a synthetic model. Every parameter (arrival rate, staffing, service times, detection rates, battery, faults, confirmation time) is an assumption written down before the first run. Nothing here is a measurement of a real robot, scanner, officer team or port, and the same author built the model and made the predictions.

## Setup
${x.seeds.length} seeds (1 to ${x.seeds.length}), ${CELL_SCENARIOS.length} scenarios, ${x.runs.length} runs. Each run has one week of arrivals at ${CELL_BASE.arrivalsPerHour} red lane containers per hour and drains the queue afterwards. Within a seed every scenario sees the same arrivals and violations. Values are means over seeds with a 95 percent t interval in brackets.

| Scenario | Containers per run | Violations per run | Serious machine findings per run | Robot faults per run |
|---|---|---|---|---|
${CELL_SCENARIOS.map((s) => `| ${s.id} ${s.name} | ${avg(s.id, 'tasks')} | ${avg(s.id, 'violations')} | ${avg(s.id, 'seriousMachineFindings')} | ${avg(s.id, 'robotFaults')} |`).join('\n')}

Conservation: in all ${x.runs.length} runs every task completed exactly once: **${result.conservation.allConserved ? 'yes' : 'NO'}**.

## Results
| Metric | ${CELL_SCENARIOS.map((s) => `${s.id} ${s.name}`).join(' | ')} |
|---|---|---|---|---|
${row('M1 median lead time (h)', 'medianLead', fh)}
${row('M2 90th percentile lead time (h)', 'p90Lead', fh)}
${row('M3 median hands on time per container (h)', 'medianHandsOn', fh)}
${row('M4 officer hours per container', 'officerHoursPerContainer', fh)}
${row('M5 missed violation share', 'missedViolationShare', fp)}
${row('M6 90th percentile confirmation delay (h)', 'p90ConfirmDelay', fh)}
${row('M7 serious machine findings confirmed before completion', 'confirmedBeforeCompletion', fp)}

## Predictions
${result.hits} of ${result.predictionCount} predictions hit; ${result.misses} missed. Misses are kept and reported as written. P6 cannot fail by construction (a task with a serious machine finding completes only at its confirmation), so it is reported as a structural check and not counted as a prediction (amendment A2): ${result.invariantsHeld ? 'it held in every run' : 'it FAILED'}. The first run, before amendment A1, also hit every prediction except P5.

| Id | Prediction | Condition for HIT | Observed | Result |
|---|---|---|---|---|
${checks.map((c) => `| ${c.id} | ${c.prediction} | ${c.condition} | ${c.observed} | ${c.kind === 'invariant' ? (c.hit ? 'HELD (structural)' : 'FAILED (structural)') : c.hit ? 'HIT' : 'MISS'} |`).join('\n')}

## Reading the results
- **The miss (P5).** Frequent robot failures did not make the cell slower than officers alone at the median: the difference is ${fh(x.diff('medianLead', 'S4', 'S1'))} h. Under the fallback rule officers take over whenever no robot is operational, so failures move work back to officers (${S.S4.officerHoursPerContainer.mean.toFixed(2)} officer hours per container in S4 against ${S.S3.officerHoursPerContainer.mean.toFixed(2)} in S3) instead of leaving containers waiting. The cost shows in the tail instead: the 90th percentile lead time is ${S.S4.p90Lead.mean.toFixed(2)} h in S4 against ${S.S1.p90Lead.mean.toFixed(2)} h in S1. The prediction was wrong about where the failures would hurt.
- **P9 and staffing.** The confirmation delay equals the 0.5 h confirmation itself because, with the same seven officers on the roster, officers in S3 are rarely busy. The result therefore depends on keeping officer capacity for confirmation. If officers were redeployed because robots do the inspections, the delay would grow; this experiment did not test that.
- **Detection is the trade.** The robot cell is faster and uses less officer time, but misses more violations than officers alone (${fp(S.S3.missedViolationShare)} against ${fp(S.S1.missedViolationShare)}). The scanner path is fastest and misses the most. Officer confirmation guards against false machine findings; it cannot recover a violation the machine did not report.
- **A slip in the preregistration.** It estimated about 13 violations per run. The correct expectation is about 20 (1.5 per hour over 168 hours at 8 percent); the observed mean is ${avg('S1', 'violations')}. This affected only the remark about statistical power, not any condition, and the preregistration is left as committed.

## What this shows and what it does not
- Under these assumptions, the comparison between ${scen('S1')} and ${scen('S3')} on lead time, hands on time and officer hours is the logic of the design made explicit, with its spread over 30 seeds. It is not evidence that any real robot achieves these rates.
- Officer confirmation is modelled as perfect: an officer always establishes the truth on site. A real officer can be wrong, and would need a measured error rate.
- The missed violation share rests on about ${avg('S1', 'violations')} violations per run, so its intervals are wide. Detection rates are the main driver and they are assumptions.
- The fallback rule (officers inspect only when no robot is operational) is one policy among several. A different rule would change ${scen('S4')} substantially.
- Arrivals are constant over the day; a real terminal has peaks, vessel waves and maintenance windows.
`;
  return { json: JSON.stringify(result, null, 2) + '\n', markdown: md };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { json, markdown } = buildCellReport();
  fs.writeFileSync('docs/cell-results.json', json);
  fs.writeFileSync('docs/cell-experiment.md', markdown);
  const r = JSON.parse(json);
  console.log(`cell experiment: ${r.conservation.runs} runs, conservation ${r.conservation.allConserved ? 'ok' : 'FAILED'}, ${r.hits} hits, ${r.misses} misses`);
  for (const p of r.predictions) console.log(`  ${p.id} ${p.kind === 'invariant' ? 'HELD' : p.hit ? 'HIT ' : 'MISS'} ${p.observed}`);
}
